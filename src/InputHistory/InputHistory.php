<?php
declare(strict_types=1);

namespace Crustum\AiInteraction\InputHistory;

use Crustum\Ai\Messages\UserMessage;
use Crustum\AiInteraction\Storage\StorageInterface;
use Crustum\AiInteraction\Storage\StoredDocument;
use UnexpectedValueException;
use function array_is_list;
use function array_key_last;
use function array_keys;
use function array_map;
use function end;
use function hash;
use function is_array;
use function is_string;
use function max;
use function trim;

/**
 * Submitted text inputs scoped to one participant.
 *
 * Histories share the same storage backend across adapters; each participant
 * reads and writes only its own scoped document.
 */
final class InputHistory
{
    /**
     * Storage namespace for input history documents.
     *
     * @var string
     */
    private const string NAMESPACE = 'input-history';

    /**
     * Storage key for histories without a participant.
     *
     * @var string
     */
    private const string ANONYMOUS_KEY = 'entries';

    /**
     * Navigation position within the stored sequence.
     *
     * @var int|null
     */
    private ?int $position = null;

    /**
     * Draft preserved while navigating older inputs.
     *
     * @var \Crustum\Ai\Messages\UserMessage|null
     */
    private ?UserMessage $draft = null;

    /**
     * Participant type owning the history.
     *
     * @var string|null
     */
    private readonly ?string $participantType;

    /**
     * Participant identifier owning the history.
     *
     * @var string|int|null
     */
    private readonly string|int|null $participantId;

    /**
     * Storage backend holding history documents.
     *
     * @var \Crustum\AiInteraction\Storage\StorageInterface
     */
    private readonly StorageInterface $storage;

    /**
     * Creates a participant-scoped input history.
     *
     * @param \Crustum\AiInteraction\Storage\StorageInterface $storage Storage backend holding history documents.
     * @param string|null $participantType Participant type owning the history.
     * @param string|int|null $participantId Participant identifier owning the history.
     */
    public function __construct(
        StorageInterface $storage,
        ?string $participantType = null,
        string|int|null $participantId = null,
    ) {
        $this->storage = $storage;
        $this->participantType = $participantType;
        $this->participantId = $participantId;
    }

    /**
     * Records the submitted input text, including command syntax.
     *
     * Blank inputs are ignored. Consecutive exact duplicates collapse into one entry.
     * Adapters must not record prompts generated by commands here.
     *
     * @param \Crustum\Ai\Messages\UserMessage $input Submitted user message.
     * @return void
     */
    public function record(UserMessage $input): void
    {
        if (trim((string)$input->content) === '') {
            return;
        }

        $entries = $this->entries();

        if ($entries !== [] && $this->sameInput(end($entries), $input)) {
            return;
        }

        $entries[] = $input;
        $data = array_map(static fn(UserMessage $message): array => ['content' => $message->content], $entries);
        $this->storage->write(self::NAMESPACE, $this->storageKey(), $data, $this->scopeMetadata());
    }

    /**
     * Moves toward older inputs, entering navigation at the newest one.
     *
     * @param \Crustum\Ai\Messages\UserMessage $draft Current composer draft preserved while navigating.
     * @return \Crustum\Ai\Messages\UserMessage|null Older input or null when history is empty.
     */
    public function older(UserMessage $draft = new UserMessage('')): ?UserMessage
    {
        $entries = $this->entries();

        if ($entries === []) {
            return null;
        }

        if ($this->position === null) {
            $this->draft = $draft;
            $this->position = array_key_last($entries);
        } else {
            $this->position = max(0, $this->position - 1);
        }

        return $entries[$this->position];
    }

    /**
     * Moves toward newer inputs, restoring the draft past the end.
     *
     * @return \Crustum\Ai\Messages\UserMessage|null Newer input, the preserved draft, or null when idle.
     */
    public function newer(): ?UserMessage
    {
        if ($this->position === null) {
            return null;
        }

        $entries = $this->entries();

        if ($this->position === array_key_last($entries)) {
            $draft = $this->draft;
            $this->leave();

            return $draft;
        }

        ++$this->position;

        return $entries[$this->position];
    }

    /**
     * Reports whether navigation is in progress.
     *
     * @return bool True while navigating stored inputs.
     */
    public function isNavigating(): bool
    {
        return $this->position !== null;
    }

    /**
     * Leaves navigation, discarding the preserved draft.
     *
     * @return void
     */
    public function leave(): void
    {
        $this->position = null;
        $this->draft = null;
    }

    /**
     * Reads the current participant sequence, oldest first.
     *
     * @return list<\Crustum\Ai\Messages\UserMessage> Stored inputs, oldest first.
     * @throws \UnexpectedValueException When the stored document is not a user message list.
     */
    public function entries(): array
    {
        $document = $this->storage->read(self::NAMESPACE, $this->storageKey());

        if (!$document instanceof StoredDocument) {
            return [];
        }

        $entries = $document->data;

        if (!array_is_list($entries)) {
            throw new UnexpectedValueException(
                'Stored input history must be a JSON array.',
            );
        }

        $decoded = [];

        foreach ($entries as $entry) {
            $decoded[] = $this->decodeEntry($entry);
        }

        if ($document->metadata !== $this->scopeMetadata()) {
            return [];
        }

        return $decoded;
    }

    /**
     * Resolves the storage key for the current scope.
     *
     * @return string Scoped storage key.
     */
    private function storageKey(): string
    {
        if ($this->participantType === null && $this->participantId === null) {
            return self::ANONYMOUS_KEY;
        }

        return hash('sha256', $this->participantType . ':' . $this->participantId);
    }

    /**
     * Builds the metadata pair identifying the current scope.
     *
     * @return array<string, string> Scope metadata pair.
     */
    private function scopeMetadata(): array
    {
        return [
            'participantType' => (string)$this->participantType,
            'participantId' => (string)$this->participantId,
        ];
    }

    /**
     * Decodes one stored entry into a user message.
     *
     * @param mixed $entry Stored entry.
     * @return \Crustum\Ai\Messages\UserMessage Decoded user message.
     * @throws \UnexpectedValueException When the entry is not a stored user message.
     */
    private function decodeEntry(mixed $entry): UserMessage
    {
        if (!is_array($entry) || array_keys($entry) !== ['content'] || !is_string($entry['content'])) {
            throw new UnexpectedValueException('Every input history entry must be a user message.');
        }

        return new UserMessage($entry['content']);
    }

    /**
     * Compares two inputs by submitted text.
     *
     * @param \Crustum\Ai\Messages\UserMessage $first First input.
     * @param \Crustum\Ai\Messages\UserMessage $second Second input.
     * @return bool True when both carry the same text.
     */
    private function sameInput(UserMessage $first, UserMessage $second): bool
    {
        return $first->content === $second->content;
    }
}
